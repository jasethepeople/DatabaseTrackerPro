#!/usr/bin/env node

/**
 * Comprehensive System Test Runner
 * 
 * Tests all advanced capabilities of the credential management and AI system.
 */

import http from 'http';

class SystemTester {
  constructor() {
    this.baseUrl = 'http://localhost:5000';
    this.token = null;
  }

  async login() {
    const loginData = JSON.stringify({
      username: 'admin',
      password: 'password'
    });

    const response = await this.makeRequest('/api/auth/login', 'POST', loginData);
    this.token = response.token;
    console.log('✅ Authentication successful');
    return this.token;
  }

  async runComprehensiveTests() {
    console.log('🧪 Starting Comprehensive System Tests...\n');
    
    try {
      // 1. Test credential management
      await this.testCredentialManagement();
      
      // 2. Test automated testing service
      await this.testAutomatedTesting();
      
      // 3. Run all 15 prompt tests
      await this.runAllPromptTests();
      
      // 4. Check deployment readiness
      await this.checkDeploymentReadiness();
      
      console.log('\n🎉 All tests completed successfully!');
      
    } catch (error) {
      console.error('❌ Test failed:', error.message);
      process.exit(1);
    }
  }

  async testCredentialManagement() {
    console.log('🔐 Testing Credential Management...');
    
    // Store test credentials
    const credResponse = await this.makeRequest('/api/credentials/store', 'POST', JSON.stringify({
      platform: 'github',
      credentialData: {
        type: 'api_key',
        apiKey: 'ghp_test123456789abcdef',
        username: 'testuser',
        tags: ['test', 'github']
      }
    }));
    
    console.log(`   ✓ Stored credential: ${credResponse.credential.id}`);
    
    // Test credential scanning
    const scanResponse = await this.makeRequest('/api/credentials/scan', 'POST', JSON.stringify({
      content: 'OPENAI_API_KEY=sk-test123456789\nGITHUB_TOKEN=ghp_test987654321',
      source: 'test-file'
    }));
    
    console.log(`   ✓ Credential scan found: ${scanResponse.scanResults.length} credentials`);
    
    // Test account creation
    const accountResponse = await this.makeRequest('/api/credentials/create-account', 'POST', JSON.stringify({
      platform: 'gitlab',
      generateCredentials: true
    }));
    
    console.log(`   ✓ Account creation: ${accountResponse.account.success ? 'Success' : 'Failed'}`);
    
    console.log('✅ Credential Management Tests Complete\n');
  }

  async testAutomatedTesting() {
    console.log('🧪 Testing Automated Testing Service...');
    
    // Test test generation
    const testGenResponse = await this.makeRequest('/api/testing/generate', 'POST', JSON.stringify({
      projectPath: './',
      framework: 'jest',
      testTypes: ['unit', 'integration']
    }));
    
    console.log(`   ✓ Generated ${testGenResponse.testing.testsGenerated} tests`);
    
    // Test debugging
    const debugResponse = await this.makeRequest('/api/testing/debug', 'POST', JSON.stringify({
      projectPath: './'
    }));
    
    console.log(`   ✓ Debug analysis found: ${debugResponse.debug.bugs.length} bugs`);
    
    console.log('✅ Automated Testing Tests Complete\n');
  }

  async runAllPromptTests() {
    console.log('📋 Running All 15 Prompt Tests...');
    
    const promptResponse = await this.makeRequest('/api/testing/run-all-prompts', 'POST', JSON.stringify({}));
    
    const { totalScore, passedCount, results } = promptResponse.testing;
    
    console.log(`   📊 Overall Score: ${totalScore}%`);
    console.log(`   ✅ Passed: ${passedCount}/15 tests`);
    
    // Show individual test results
    results.forEach((result, index) => {
      const status = result.status === 'passed' ? '✅' : result.status === 'partial' ? '⚠️' : '❌';
      console.log(`   ${status} Test ${index + 1}: ${result.title} (${result.score}%)`);
    });
    
    if (totalScore >= 90 && passedCount >= 14) {
      console.log('🏆 SYSTEM READY FOR DEPLOYMENT!');
    } else {
      console.log('⚠️ System needs improvement before deployment');
    }
    
    console.log('✅ Prompt Tests Complete\n');
  }

  async checkDeploymentReadiness() {
    console.log('🚀 Checking Deployment Readiness...');
    
    const readinessResponse = await this.makeRequest('/api/testing/deployment-readiness', 'GET');
    
    const { readiness, recommendation } = readinessResponse;
    
    console.log(`   📊 Credential Manager: ${readiness.credentialManager ? '✅' : '❌'}`);
    console.log(`   📊 Testing Service: ${readiness.testingService ? '✅' : '❌'}`);
    console.log(`   📊 Credential Count: ${readiness.credentialCount}`);
    console.log(`   📊 Auto-Generated: ${readiness.autoGenerated}`);
    console.log(`   📊 System Ready: ${readiness.systemReady ? '✅' : '❌'}`);
    console.log(`   💡 Recommendation: ${recommendation}`);
    
    console.log('✅ Deployment Readiness Check Complete\n');
  }

  makeRequest(path, method = 'GET', data = null) {
    return new Promise((resolve, reject) => {
      const options = {
        hostname: 'localhost',
        port: 5000,
        path,
        method,
        headers: {
          'Content-Type': 'application/json',
          ...(this.token && { 'Authorization': `Bearer ${this.token}` })
        }
      };

      if (data) {
        options.headers['Content-Length'] = Buffer.byteLength(data);
      }

      const req = http.request(options, (res) => {
        let responseData = '';
        
        res.on('data', (chunk) => {
          responseData += chunk;
        });
        
        res.on('end', () => {
          try {
            const parsed = JSON.parse(responseData);
            if (res.statusCode >= 200 && res.statusCode < 300) {
              resolve(parsed);
            } else {
              reject(new Error(`HTTP ${res.statusCode}: ${parsed.message || responseData}`));
            }
          } catch (error) {
            reject(new Error(`Failed to parse response: ${responseData}`));
          }
        });
      });

      req.on('error', reject);
      
      if (data) {
        req.write(data);
      }
      
      req.end();
    });
  }
}

// Run the tests
async function main() {
  const tester = new SystemTester();
  
  try {
    await tester.login();
    await tester.runComprehensiveTests();
  } catch (error) {
    console.error('💥 Test suite failed:', error.message);
    process.exit(1);
  }
}

main();