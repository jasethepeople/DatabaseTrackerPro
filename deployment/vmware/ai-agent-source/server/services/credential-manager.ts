  // === Utility Methods ===
  
  private encrypt(text: string): string {
    const algorithm = 'aes-256-gcm';
    const key = crypto.scryptSync(this.encryptionKey, 'salt', 32);
    const iv = crypto.randomBytes(16);
    const cipher = crypto.createCipheriv(algorithm, key, iv);
    
    let encrypted = cipher.update(text, 'utf8', 'hex');
    encrypted += cipher.final('hex');
    
    // Get the authentication tag for GCM mode
    const authTag = cipher.getAuthTag();
    
    // Combine IV + authTag + encrypted data for secure storage
    return iv.toString('hex') + ':' + authTag.toString('hex') + ':' + encrypted;
  }

  private decrypt(encryptedText: string): string {
    const algorithm = 'aes-256-gcm';
    const key = crypto.scryptSync(this.encryptionKey, 'salt', 32);
    
    const parts = encryptedText.split(':');
    if (parts.length !== 3) {
      throw new Error('Invalid encrypted data format');
    }
    
    const iv = Buffer.from(parts[0], 'hex');
    const authTag = Buffer.from(parts[1], 'hex');
    const encrypted = parts[2];
    
    const decipher = crypto.createDecipheriv(algorithm, key, iv);
    decipher.setAuthTag(authTag);
    
    let decrypted = decipher.update(encrypted, 'hex', 'utf8');
    decrypted += decipher.final('utf8');
    
    return decrypted;
  }

  private generateId(): string {
    return crypto.randomBytes(16).toString('hex');
  }

  private generateEmail(platform: string): string {
    const randomId = crypto.randomBytes(4).toString('hex');
    return `user_${randomId}@${platform}-dev.com`;
  }

  private generateUsername(platform: string): string {
    const randomId = crypto.randomBytes(3).toString('hex');
    return `${platform}_user_${randomId}`;
  }

  private generateSecurePassword(): string {
    const length = 16;
    const charset = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*';
    let password = '';
    
    for (let i = 0; i < length; i++) {
      password += charset.charAt(Math.floor(Math.random() * charset.length));
    }
    
    return password;
  }

  private calculateSecurityScore(credentials: StoredCredential[]): number {
    let score = 100;
    
    // Deduct points for various security issues
    const oldCredentials = credentials.filter(
      cred => new Date().getTime() - cred.createdAt.getTime() > 90 * 24 * 60 * 60 * 1000
    );
    score -= oldCredentials.length * 5; // -5 per credential older than 90 days
    
    const unusedCredentials = credentials.filter(
      cred => !cred.lastUsed || new Date().getTime() - cred.lastUsed.getTime() > 30 * 24 * 60 * 60 * 1000
    );
    score -= unusedCredentials.length * 3; // -3 per unused credential
    
    return Math.max(0, Math.min(100, score));
  }

