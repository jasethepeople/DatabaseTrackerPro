  // === Core Credential Management ===
  
  async storeCredential(userId: number, platform: string, credentialData: CredentialData): Promise<StoredCredential> {
    const id = this.generateId();
    const encryptedData = this.encrypt(JSON.stringify(credentialData));
    
    const credential: StoredCredential = {
      id,
      userId,
      platform,
      credentialType: credentialData.type,
      username: credentialData.username,
      email: credentialData.email,
      encryptedData,
      isActive: true,
      createdAt: new Date(),
      updatedAt: new Date(),
      tags: credentialData.tags || [],
      autoGenerated: false
    };

    this.credentials.set(id, credential);
    this.logAudit('STORE_CREDENTIAL', userId, { platform, type: credentialData.type });
    
    return credential;
  }

  async getCredentials(userId: number, platform?: string): Promise<StoredCredential[]> {
    const userCredentials = Array.from(this.credentials.values())
      .filter(cred => cred.userId === userId);
    
    if (platform) {
      return userCredentials.filter(cred => cred.platform === platform);
    }
    
    return userCredentials;
  }

  async getCredentialData(credentialId: string): Promise<CredentialData> {
    const credential = this.credentials.get(credentialId);
    if (!credential) {
      throw new Error('Credential not found');
    }

    const decryptedData = this.decrypt(credential.encryptedData);
    return JSON.parse(decryptedData);
  }

  async getCredentialStats(userId: number): Promise<CredentialStats> {
    const userCredentials = await this.getCredentials(userId);
    
    const byType: Record<string, number> = {};
    const byPlatform: Record<string, number> = {};
    let autoGenerated = 0;
    let lastActivity = new Date(0);

    for (const cred of userCredentials) {
      byType[cred.credentialType] = (byType[cred.credentialType] || 0) + 1;
      byPlatform[cred.platform] = (byPlatform[cred.platform] || 0) + 1;
      
      if (cred.autoGenerated) autoGenerated++;
      if (cred.lastUsed && cred.lastUsed > lastActivity) {
        lastActivity = cred.lastUsed;
      }
    }

    return {
      total: userCredentials.length,
      byType,
      byPlatform,
      autoGenerated,
      lastActivity: lastActivity.getTime() > 0 ? lastActivity : new Date(),
      securityScore: this.calculateSecurityScore(userCredentials)
    };
  }

  // === Automatic Credential Scanning ===
  
  async scanForCredentials(content: string, source: string): Promise<ScanResult[]> {
    const results: ScanResult[] = [];
    
    // Scan for API keys
    const apiKeyPatterns = [
      { pattern: /sk-[a-zA-Z0-9]{48}/, platform: 'openai', type: 'api_key' },
      { pattern: /AKIA[0-9A-Z]{16}/, platform: 'aws', type: 'api_key' },
      { pattern: /AIza[0-9A-Za-z_-]{35}/, platform: 'google', type: 'api_key' },
      { pattern: /pk_test_[0-9a-zA-Z]{24}/, platform: 'stripe', type: 'api_key' },
      { pattern: /ghp_[a-zA-Z0-9]{36}/, platform: 'github', type: 'api_key' },
    ];

    for (const { pattern, platform, type } of apiKeyPatterns) {
      const matches = content.match(pattern);
      if (matches) {
        for (const match of matches) {
          results.push({
            type,
            platform,
            confidence: 0.95,
            data: { type: 'api_key', apiKey: match },
            source,
            location: `Pattern match: ${pattern.source}`
          });
        }
      }
    }

    // Scan for passwords in environment files
    const envPatterns = [
      /(\w+_PASSWORD|PASSWORD|PWD)=([^\s\n]+)/gi,
      /(\w+_SECRET|SECRET|API_SECRET)=([^\s\n]+)/gi,
      /(\w+_KEY|KEY|API_KEY)=([^\s\n]+)/gi,
    ];

    for (const pattern of envPatterns) {
      let match;
      while ((match = pattern.exec(content)) !== null) {
        results.push({
          type: 'password',
          platform: 'environment',
          confidence: 0.8,
          data: { 
            type: 'password', 
            username: match[1], 
            password: match[2],
            metadata: { envVar: match[1] }
          },
          source,
          location: `Environment variable: ${match[1]}`
        });
      }
    }

    // Scan for database connection strings
    const dbPatterns = [
      /mongodb:\/\/([^:]+):([^@]+)@([^\/]+)/gi,
      /postgres:\/\/([^:]+):([^@]+)@([^\/]+)/gi,
      /mysql:\/\/([^:]+):([^@]+)@([^\/]+)/gi,
    ];

    for (const pattern of dbPatterns) {
      let match;
      while ((match = pattern.exec(content)) !== null) {
        results.push({
          type: 'password',
          platform: 'database',
          confidence: 0.9,
          data: {
            type: 'password',
            username: match[1],
            password: match[2],
            metadata: { host: match[3] }
          },
          source,
          location: `Database connection string`
        });
      }
    }

    this.logAudit('SCAN_CREDENTIALS', 0, { source, foundCount: results.length });
    return results;
  }

  async autoStoreFoundCredentials(userId: number, scanResults: ScanResult[]): Promise<StoredCredential[]> {
    const stored: StoredCredential[] = [];
    
    for (const result of scanResults) {
      try {
        const credential = await this.storeCredential(userId, result.platform, {
          ...result.data,
          tags: ['auto-discovered', result.source],
          metadata: { 
            confidence: result.confidence,
            scanLocation: result.location,
            autoGenerated: true
          }
        });
        
        credential.autoGenerated = true;
        stored.push(credential);
      } catch (error) {
        console.error('Failed to auto-store credential:', error);
      }
    }

    this.logAudit('AUTO_STORE_CREDENTIALS', userId, { count: stored.length });
    return stored;
  }

